"""Generate native PHP job-status vocabulary from the imported, verified Core.

Do not maintain PHP statuses by hand. CI uses --check to fail closed if Core
adds, removes, or reclassifies a job status without updating the bridge.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from app.job_states import JobStatus, TERMINAL_STATUSES

OUTPUT = Path(__file__).resolve().parents[1] / "bridge/lib/JobStateContract.php"
STATUS_PATTERN = re.compile(r"[a-z][a-z-]*\\Z")


def php_array(values: list[str]) -> str:
    if not values or any(STATUS_PATTERN.fullmatch(value) is None for value in values):
        raise ValueError("Invalid Core job-status vocabulary")
    return "[" + ", ".join("'" + value + "'" for value in values) + "]"


def render() -> str:
    all_states = sorted(status.value for status in JobStatus)
    terminal = sorted(status.value for status in TERMINAL_STATUSES)
    if not set(terminal).issubset(all_states):
        raise ValueError("Core terminal status is not a declared status")
    return (
        "<?php\n"
        "declare(strict_types=1);\n\n"
        "namespace OCA\\DownloaderBridge;\n\n"
        "// GENERATED by scripts/bridge_job_state_contract.py from Core app/job_states.py.\n"
        "// Do not edit: run python -m scripts.bridge_job_state_contract.\n"
        "final class JobStateContract {\n"
        f"    public const ALL = {php_array(all_states)};\n"
        f"    public const TERMINAL = {php_array(terminal)};\n\n"
        "    public static function isTerminal(mixed $status): bool {\n"
        "        return is_string($status) && in_array($status, self::TERMINAL, true);\n"
        "    }\n"
        "}\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Fail if the tracked PHP bridge differs from canonical Core")
    args = parser.parse_args()
    expected = render()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text(encoding="utf-8") != expected:
            raise SystemExit(
                "PHP job-state contract differs from Core. "
                "Run python -m scripts.bridge_job_state_contract and commit the result."
            )
        print("PHP job-state contract matches the imported Core enum and terminal set")
    else:
        OUTPUT.write_text(expected, encoding="utf-8")
        print("Regenerated", OUTPUT)


if __name__ == "__main__":
    main()
