"""Generate native PHP AND packaged ExApp Python status vocabularies from Core.

Only the verified upstream app/job_states.py may define job statuses. These
small generated leaf modules are packaged separately so the ExApp runtime
does not import the independently deployed Core Python service. --check
fails closed in CI if either generated consumer drifts from Core.
"""
from __future__ import annotations

import argparse
import re
from pathlib import Path

from app.job_states import JobStatus, TERMINAL_STATUSES

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "bridge/lib/JobStateContract.php"
PYTHON_OUTPUT = ROOT / "nextcloud_exapp/job_state_contract.py"
STATUS_PATTERN = re.compile(r"[a-z][a-z-]*\Z")


def vocabulary() -> tuple[list[str], list[str]]:
    all_states = sorted(status.value for status in JobStatus)
    terminal = sorted(status.value for status in TERMINAL_STATUSES)
    if not terminal or not set(terminal).issubset(all_states):
        raise ValueError("Core terminal statuses must be nonempty declared states")
    if any(STATUS_PATTERN.fullmatch(value) is None for value in all_states):
        raise ValueError("Invalid Core job-status vocabulary")
    return all_states, terminal


def php_array(values: list[str]) -> str:
    return "[" + ", ".join("'" + value + "'" for value in values) + "]"


def render() -> str:
    all_states, terminal = vocabulary()
    return (
        "<?php\n"
        "declare(strict_types=1);\n\n"
        "namespace OCA\\DownloaderBridge;\n\n"
        "// GENERATED by scripts/bridge_job_state_contract.py from Core app/job_states.py.\n"
        "// Do not edit: run python -m scripts.bridge_job_state_contract.\n"
        "final class JobStateContract {\n"
        f"    public const ALL = {php_array(all_states)};\n"
        f"    public const TERMINAL = {php_array(terminal)};\n\n"
        "    public static function isTerminal(mixed $status): bool {\n"
        "        return is_string($status) && in_array($status, self::TERMINAL, true);\n"
        "    }\n"
        "}\n"
    )


def render_python() -> str:
    all_states, terminal = vocabulary()
    return (
        '"""Generated from the verified Core job-state enum; do not edit by hand."""\n'
        "from __future__ import annotations\n\n"
        "# Generated by scripts/bridge_job_state_contract.py; tracked and checked in CI.\n"
        f"ALL_STATES = frozenset({tuple(all_states)!r})\n"
        f"TERMINAL_STATES = frozenset({tuple(terminal)!r})\n"
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Fail if either packaged consumer differs from canonical Core")
    args = parser.parse_args()
    expected = {OUTPUT: render(), PYTHON_OUTPUT: render_python()}
    if args.check:
        for path, source in expected.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != source:
                raise SystemExit(
                    f"Generated job-state contract {path} differs from imported Core. "
                    "Run python -m scripts.bridge_job_state_contract and commit both consumers."
                )
        print("PHP and packaged ExApp Python contracts match the imported Core status enum")
    else:
        for path, source in expected.items():
            path.write_text(source, encoding="utf-8")
            print("Regenerated", path)


if __name__ == "__main__":
    main()
